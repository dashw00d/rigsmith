// Writes src/model/template-parents.ts: each creature template's joints and their parents, in the template's order,
// from static/templates/<id>.json (`order`, `parents`). A table in code so hierarchies stay synchronous and the app
// doesn't bundle the templates' rest poses. Run it after changing a template: node src/model/template-parents.gen.ts
// (skeletons.test.ts fails while the two disagree).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..', '..')
const DIR = path.join(ROOT, 'static', 'templates')
const WIDTH = 120

const q = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const key = (s: string): string => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : q(s))

const blocks: string[] = []
for (const file of readdirSync(DIR).filter(f => f.endsWith('.json')).sort()) {
  const t = JSON.parse(readFileSync(path.join(DIR, file), 'utf8')) as { order?: string[], parents?: Record<string, string | null> }
  if (t.order === undefined || t.parents === undefined) continue
  const lines: string[] = []
  let line = '   '
  for (const joint of t.order) {
    const parent = t.parents[joint]
    const entry = ` ${key(joint)}: ${parent === null || parent === undefined ? 'null' : q(parent)},`
    if (line.length + entry.length > WIDTH) { lines.push(line); line = '   ' }
    line += entry
  }
  lines.push(line)
  blocks.push(`  ${key(path.basename(file, '.json'))}: {\n${lines.join('\n')}\n  },`)
}

const out = `// Generated by \`node src/model/template-parents.gen.ts\` from static/templates/<id>.json (each creature template's
// \`order\` and \`parents\`). Don't edit it: change the template and run that again (skeletons.test.ts checks they agree).
export const TEMPLATE_PARENTS: Record<string, Record<string, string | null>> = {
${blocks.join('\n')}
}
`
writeFileSync(path.join(import.meta.dirname, 'template-parents.ts'), out)
